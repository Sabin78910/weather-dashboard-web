export const t = (lang: Lang, key: Key, params: Record<string, string | number> = {}): string =>
  (lang === "ne" ? NE : EN)[key].replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));

const DEVANAGARI = "०१२३४५६७८९";
/** Renders digits in the language's numerals (Devanagari for Nepali). */
export const num = (lang: Lang, n: number | string): string =>
  lang === "ne" ? String(n).replace(/\d/g, (d) => DEVANAGARI[Number(d)]) : String(n);

export const locale = (lang: Lang): string | undefined => (lang === "ne" ? "ne-NP" : undefined);

export const formatDateTime = (lang: Lang, ms: number): string => num(lang, new Date(ms).toLocaleString(locale(lang)));
export const formatWeekday = (lang: Lang, date: string): string =>
  num(lang, new Date(date).toLocaleDateString(locale(lang), { weekday: "short", day: "numeric" }));

/** Language from the browser setting; Nepali only for ne*, English otherwise. */
export const detectLang = (): Lang => (typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("ne") ? "ne" : "en");
